"""`testing.flows.find_seeded_dataset`: how test_seed_demo maps a seeded CSV to its dataset (no database needed).

`manage.py seed_demo` ingests EVERY top-level CSV of testdata/generated/ (12 files, including customers_crm.csv,
customers_web.csv, products_supplier_a/b.csv) and the dataset list is newest-first. A substring match on the
name therefore picked "Customers (web sign-ups)" for customers.csv and "Products (supplier B)" for products.csv
(review finding W3). The matcher must pick exactly the dataset made from the file, or fail loudly.

Names and descriptions follow Backend W3 `apps.platform_admin.demo` (its real `dataset_name_for` / `csv_files`
are used when importable; otherwise the same rules are mirrored here).
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

from testing.flows import find_seeded_dataset, normalised_name

REPO = Path(__file__).resolve().parents[3]
GEN = REPO / "testdata" / "generated"
SEED_FILES = ("sales.csv", "customers.csv", "products.csv", "orders.csv", "support_tickets.csv")

# Backend W3 apps.platform_admin.demo.DATASET_NAMES (mirrored for when the module is not merged yet).
_MIRRORED_NAMES = {
    "sales.csv": "Sales",
    "churn.csv": "Customer churn",
    "customers_crm.csv": "Customers (CRM)",
    "customers_web.csv": "Customers (web sign-ups)",
    "customers_ground_truth.csv": "Customer identity ground truth",
    "products_supplier_a.csv": "Products (supplier A)",
    "products_supplier_b.csv": "Products (supplier B)",
    "products_ground_truth.csv": "Product master ground truth",
}


def _naming():
    if importlib.util.find_spec("apps.platform_admin") and importlib.util.find_spec(
        "apps.platform_admin.demo"
    ):
        from apps.platform_admin import demo

        return demo.dataset_name_for, demo.csv_files

    def dataset_name_for(path: Path) -> str:
        return _MIRRORED_NAMES.get(path.name) or path.stem.replace("_", " ").strip().capitalize()

    def csv_files(directory: Path) -> list[Path]:
        files = sorted(p for p in directory.glob("*.csv") if p.is_file())
        return sorted(files, key=lambda p: (p.name != "sales.csv", p.name))

    return dataset_name_for, csv_files


def _seeded_listing() -> list[dict]:
    """The dataset list after seed_demo, as GET /datasets returns it (newest first)."""
    dataset_name_for, csv_files = _naming()
    created = [
        {
            "id": f"ds-{i:02d}",
            "name": dataset_name_for(path),
            "description": f"Synthetic demo data ({path.name}, generated by testdata/generate.py).",
            "_file": path.name,
        }
        for i, path in enumerate(csv_files(GEN))
    ]
    return list(reversed(created))


def test_the_generated_data_has_the_confusable_files():
    names = {p.name for p in GEN.glob("*.csv")}
    assert set(SEED_FILES) <= names
    assert {
        "customers_crm.csv",
        "customers_web.csv",
        "products_supplier_a.csv",
        "products_supplier_b.csv",
    } <= names


def test_the_old_substring_match_picked_the_wrong_dataset():
    """Documents the defect: the previous `stem in key or key in stem` rule with match[0]."""
    listing = _seeded_listing()
    wrong = []
    for name in SEED_FILES:
        stem = normalised_name(Path(name).stem)
        match = [
            d for d in listing if stem in normalised_name(d["name"]) or normalised_name(d["name"]) in stem
        ]
        if match[0]["_file"] != name:
            wrong.append((name, match[0]["name"]))
    assert {w[0] for w in wrong} >= {"customers.csv", "products.csv"}, wrong


@pytest.mark.parametrize("name", SEED_FILES)
def test_each_seed_file_maps_to_exactly_its_own_dataset(name):
    listing = _seeded_listing()
    assert find_seeded_dataset(listing, name)["_file"] == name
    # also by name alone (a backend that writes no description) ...
    no_desc = [{**d, "description": ""} for d in listing]
    assert find_seeded_dataset(no_desc, name)["_file"] == name


def test_description_identifies_a_renamed_dataset():
    listing = [
        {**d, "name": "Renamed by a user"} if d["_file"] == "orders.csv" else d for d in _seeded_listing()
    ]
    assert find_seeded_dataset(listing, "orders.csv")["_file"] == "orders.csv"


def test_ambiguous_or_missing_matches_fail_loudly():
    listing = _seeded_listing()
    twin = {"id": "ds-twin", "name": "Customers", "description": "", "_file": "?"}
    with pytest.raises(pytest.fail.Exception, match="exactly one"):
        find_seeded_dataset([twin, *listing], "customers.csv")
    without = [d for d in listing if d["_file"] != "support_tickets.csv"]
    with pytest.raises(pytest.fail.Exception, match="found 0"):
        find_seeded_dataset(without, "support_tickets.csv")
