"""The committed synthetic test data is deterministic and has the documented properties (testdata/README.md)."""

from __future__ import annotations

import csv
import datetime as dt
import importlib.util
import json
import zipfile
from collections import Counter
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[3]
GEN_DIR = REPO / "testdata" / "generated"
MANIFEST = json.loads((GEN_DIR / "MANIFEST.json").read_text(encoding="utf-8"))


def _load_generator():
    spec = importlib.util.spec_from_file_location(
        "nexora_testdata_generate", REPO / "testdata" / "generate.py"
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _rows(name: str) -> list[dict]:
    with (GEN_DIR / name).open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def test_generation_is_deterministic(tmp_path):
    gen = _load_generator()
    manifest = gen.generate(tmp_path, dt.date.fromisoformat(MANIFEST["anchor"]))
    assert manifest["files"] == MANIFEST["files"], "regenerated bytes differ from the committed files"


def test_committed_files_match_manifest():
    gen = _load_generator()
    for name, info in MANIFEST["files"].items():
        path = GEN_DIR / name
        assert path.stat().st_size == info["bytes"], name
        assert gen._sha256(path) == info["sha256"], name


def test_sales_properties():
    rows = _rows("sales.csv")
    assert list(rows[0]) == [
        "order_id",
        "order_date",
        "customer_id",
        "customer_name",
        "region",
        "product",
        "category",
        "quantity",
        "unit_price",
        "discount",
        "revenue",
        "channel",
    ]
    assert len(rows) == 5020
    ids = Counter(r["order_id"] for r in rows)
    assert len(ids) == 5000
    exact_dups = Counter(tuple(r.values()) for r in rows)
    assert sum(n - 1 for n in exact_dups.values() if n > 1) == 20
    assert {r["region"] for r in rows} - {""} == {"North", "South", "East", "West", "Central"}
    for col in ("customer_name", "region", "discount", "channel"):
        assert 0 < sum(1 for r in rows if r[col] == "") <= 10, col
    anchor = dt.date.fromisoformat(MANIFEST["anchor"])
    dates = sorted(dt.date.fromisoformat(r["order_date"]) for r in rows)
    assert dates[-1] <= anchor and (dates[-1].year, dates[-1].month) == (anchor.year, anchor.month)
    assert (anchor - dates[0]).days > 690  # ~2 years
    for r in rows:
        if r["discount"]:
            expected = round(int(r["quantity"]) * float(r["unit_price"]) * (1 - float(r["discount"])), 2)
            assert abs(expected - float(r["revenue"])) < 0.011, r["order_id"]
    by_month = Counter(r["order_date"][5:7] for r in rows)
    assert by_month["10"] > by_month["07"] * 1.4  # festive peak vs monsoon dip


def test_customer_ground_truth_is_consistent():
    crm = {r["crm_id"]: r for r in _rows("customers_crm.csv")}
    web = {r["web_id"]: r for r in _rows("customers_web.csv")}
    truth = _rows("customers_ground_truth.csv")
    matched = [t for t in truth if t["crm_id"] and t["web_id"]]
    assert len(crm) == 500 and len(web) == 450 and len(matched) == 350
    assert all(t["crm_id"] in crm for t in truth if t["crm_id"])
    assert all(t["web_id"] in web for t in truth if t["web_id"])
    # the overlap is intentionally messy: not all matches are exact on name/email
    exact = sum(
        1
        for t in matched
        if web[t["web_id"]]["full_name"]
        == f"{crm[t['crm_id']]['first_name']} {crm[t['crm_id']]['last_name']}"
        and web[t["web_id"]]["email"] == crm[t["crm_id"]]["email"]
    )
    assert 0 < exact < len(matched)
    for r in list(crm.values()) + list(web.values()):
        assert r["email"].lower().rsplit("@", 1)[1] in {
            "example.com",
            "example.org",
            "example.net",
            "mail.example.test",
        }


def test_product_ground_truth_is_consistent():
    a = {r["sku"] for r in _rows("products_supplier_a.csv")}
    b = {r["item_code"] for r in _rows("products_supplier_b.csv")}
    truth = _rows("products_ground_truth.csv")
    assert len(truth) == 200
    assert {t["supplier_a_sku"] for t in truth if t["supplier_a_sku"]} == a
    assert {t["supplier_b_item_code"] for t in truth if t["supplier_b_item_code"]} == b
    assert sum(1 for t in truth if t["supplier_a_sku"] and t["supplier_b_item_code"]) == 139
    uoms = {r["uom"] for r in _rows("products_supplier_b.csv")}
    assert {"G", "KG"} & uoms and {"ML", "L"} & uoms  # unit conversions present


def test_churn_is_labelled_with_a_known_ceiling():
    rows = _rows("churn.csv")
    meta = json.loads((GEN_DIR / "churn_meta.json").read_text(encoding="utf-8"))
    assert len(rows) == meta["rows"] == 3000
    rate = sum(int(r["churned"]) for r in rows) / len(rows)
    assert abs(rate - meta["positive_rate"]) < 1e-3 and 0.1 < rate < 0.5
    assert 0.7 < meta["oracle_auc"] < 0.95


def test_adversarial_files():
    adv = GEN_DIR / "adversarial"
    with zipfile.ZipFile(adv / "zip_bomb.xlsx") as zf:  # central directory only: never inflate it here
        total = sum(i.file_size for i in zf.infolist())
    size = (adv / "zip_bomb.xlsx").stat().st_size
    assert size < 512 * 1024 and total / size > 100
    raw = (adv / "malformed.csv").read_bytes()
    assert b"\x00" in raw and raw.startswith(b"\xef\xbb\xbf")
    with pytest.raises(UnicodeDecodeError):
        raw.decode("utf-8")
    assert (adv / "png_as.csv").read_bytes().startswith(b"\x89PNG")
    assert (adv / "mz_as.csv").read_bytes().startswith(b"MZ")
    assert not zipfile.is_zipfile(adv / "text_as.xlsx")
    cells = [r["note"] for r in _rows("adversarial/formula_injection.csv")]
    assert {c[0] for c in cells} >= {"=", "+", "-", "@", "\t", "\r"}
    old_limit = csv.field_size_limit(4 * 1024 * 1024)
    try:
        with (adv / "huge_column.csv").open(newline="", encoding="utf-8") as fh:
            big = max(len(c) for row in csv.reader(fh) for c in row)
    finally:
        csv.field_size_limit(old_limit)
    assert big > 1024 * 1024
