class SeedError(RuntimeError):
    pass


@dataclass
class DatasetResult:
    file: str
    name: str
    dataset_id: str | None = None
    status: str = "missing"
    rows: int | None = None
    columns: int | None = None
    quality: float | None = None
    error: str = ""
    action: str = "kept"


@dataclass
class SeedResult:
    email: str
    password: str | None
    password_note: str
    user_created: bool
    org_id: str
    org_slug: str
    org_name: str
    org_created: bool
    ai_data_policy: str
    datasets: list[DatasetResult] = field(default_factory=list)
    conversation_id: str | None = None
    dashboard_id: str | None = None
    widgets: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def total_rows(self) -> int:
        return sum(d.rows or 0 for d in self.datasets if d.status == "ready")


# ------------------------------------------------------------------------------------------------ helpers
def data_dir() -> Path:
    return Path(settings.REPO_DIR) / "testdata" / "generated"


def generator_script() -> Path:
    return Path(settings.REPO_DIR) / "testdata" / "generate.py"


def csv_files(directory: Path) -> list[Path]:
    """Top-level CSVs only (adversarial/ holds hostile files for security tests, never demo data)."""
    if not directory.is_dir():
        return []
    files = sorted(p for p in directory.glob("*.csv") if p.is_file())
    return sorted(files, key=lambda p: (p.name != SALES_FILE, p.name))  # sales first: the dashboard needs it


def ensure_test_data(directory: Path, *, run: Callable = subprocess.run) -> list[Path]:
    files = csv_files(directory)
    if files:
        return files
    script = generator_script()
    if not script.is_file():
        raise SeedError(f"No CSV files in {directory} and the generator {script} is missing.")
    run([sys.executable, str(script), "--out", str(directory)], check=True, cwd=str(script.parent))
    files = csv_files(directory)
    if not files:
        raise SeedError(f"testdata/generate.py produced no CSV files in {directory}.")
    return files


def dataset_name_for(path: Path) -> str:
    return DATASET_NAMES.get(path.name) or path.stem.replace("_", " ").strip().capitalize()


def generate_password(length: int = 20) -> str:
    """A strong random password with upper, lower, digit and symbol characters."""
    alphabet = string.ascii_letters + string.digits + "-_.!@#%"
    while True:
        pw = "".join(secrets.choice(alphabet) for _ in range(length))
        if (any(c.islower() for c in pw) and any(c.isupper() for c in pw) and any(c.isdigit() for c in pw)
                and any(c in "-_.!@#%" for c in pw)):
            return pw


@contextmanager
def eager_tasks():
    """Force the inline task runner for the duration of the seed (restored afterwards)."""
    previous = settings.TASK_RUNNER
    settings.TASK_RUNNER = "eager"
    try:
        yield
    finally:
        settings.TASK_RUNNER = previous


@contextmanager
def acting_as(user_id: UUID):
    from apps.core.tenancy.context import current_actor

    token = current_actor.set(("user", user_id))
    try:
        yield
    finally:
        current_actor.reset(token)


# ------------------------------------------------------------------------------------------------ steps
def _find_org(user_id: UUID, org_name: str) -> dict | None:
    from apps.orgs.services import user_orgs

    for item in user_orgs(user_id):
        if item["name"] == org_name and item["role"] == "owner":
            return item
    return None


def _seed_state() -> dict:
    from apps.orgs.services import get_current_org

    return dict((get_current_org().settings or {}).get(SEED_KEY) or {})


def _save_state(state: dict) -> None:
    from apps.orgs.services import get_current_org, update_organization

    update_organization(get_current_org(), settings_patch={SEED_KEY: state})


def _dataset(dataset_id):
    from rest_framework.exceptions import NotFound

    from apps.datasets import services as datasets

    if not dataset_id:
        return None
    try:
        return datasets.get_dataset(dataset_id)
    except NotFound:
        return None


def _reset(org_id: UUID, user_id: UUID, state: dict) -> None:
    from apps.bi import services as bi
    from apps.core.tenancy import tenant_context
    from apps.datasets import services as datasets

    with tenant_context(org_id):
        if state.get("dashboard_id"):
            dash = bi.visible_dashboards(user_id).filter(id=state["dashboard_id"], owner_id=user_id).first()
            if dash is not None:
                bi.delete_dashboard(dash, delete_owned_queries=True)
        if state.get("conversation_id"):
            bi.delete_conversation(user_id=user_id, conversation_id=state["conversation_id"])
        for dataset_id in (state.get("datasets") or {}).values():
            ds = _dataset(dataset_id)
            if ds is not None:
                datasets.soft_delete(ds)
        _save_state({})


def _ingest(org_id: UUID, user_id: UUID, path: Path, existing_id: str | None) -> DatasetResult:
    """Upload + ingest one CSV through the public dataset services (eager: finishes before returning)."""
    from django.core.files import File

    from apps.core.tenancy import tenant_context
    from apps.datasets import services as datasets

    result = DatasetResult(file=path.name, name=dataset_name_for(path))
    with tenant_context(org_id):
        ds = _dataset(existing_id)
        if ds is not None and ds.status == "ready":
            result.dataset_id = str(ds.id)
            result.action = "kept"
        else:
            with open(path, "rb") as fh:
                upload = datasets.create_upload(File(fh, name=path.name), user_id=user_id)
            if ds is None:
                ds, _job = datasets.create_dataset(
                    name=result.name, upload_id=upload.id, classification="synthetic", attest=True,
                    description=f"Synthetic demo data ({path.name}, generated by testdata/generate.py).",
                    tags=["demo", "synthetic"], user_id=user_id)
                result.action = "created"
            else:
                datasets.add_version(ds, upload_id=upload.id, user_id=user_id)
                result.action = "re-ingested"
            result.dataset_id = str(ds.id)
    # The transaction above has committed: its on_commit hook ran the (eager) ingestion. Read the outcome.
    with tenant_context(org_id):
        ds = _dataset(result.dataset_id)
        if ds is None:
            result.status, result.error = "missing", "The dataset disappeared during ingestion."
            return result
        result.status = ds.status
        result.rows, result.columns = ds.row_count, ds.column_count
        result.quality = float(ds.quality_score) if ds.quality_score is not None else None
        if ds.status != "ready":
            err = ds.last_error or {}
            result.error = f"{err.get('code', 'ingest_failed')}: {err.get('message', '')}".strip(": ")
    return result


def _ask(org_id: UUID, user_id: UUID, tenant, conversation_id: UUID, question: str) -> tuple[str | None, str]:
    """Ask one question through the real chat pipeline. Returns (assistant message id | None, error code)."""
    from apps.bi import services as bi
    from apps.core.tenancy import tenant_context

    with tenant_context(org_id, info=tenant):
        conv = bi.get_conversation(user_id, conversation_id)
        if conv is None:
            return None, "conversation_missing"
        turn = bi.start_turn(conv, question, user_id=user_id, tenant=tenant)
    events = bi.run_to_completion(turn)
    last_event, data = events[-1] if events else ("error", {"code": "no_events"})
    if last_event == "done" and data.get("status") == "ok":
        return str(turn.message_id), ""
    return None, str(data.get("code") or data.get("status") or "not_answered")


def _seed_bi(org_id: UUID, user_id: UUID, tenant, sales_id: str, state: dict, out: SeedResult) -> None:
    from apps.bi import services as bi
    from apps.core.tenancy import tenant_context

    with tenant_context(org_id, info=tenant):
        existing = None
        if state.get("dashboard_id"):
            existing = bi.visible_dashboards(user_id).filter(id=state["dashboard_id"]).first()
        if existing is not None:
            out.dashboard_id = str(existing.id)
            out.conversation_id = state.get("conversation_id")
            out.widgets = [w["title"] for w in bi.dashboard_payload(existing)["widgets"]]
            return
        conv = bi.get_conversation(user_id, state["conversation_id"]) if state.get("conversation_id") else None
        if conv is None:
            conv = bi.create_conversation(user_id=user_id, dataset_id=UUID(sales_id), title=CONVERSATION_TITLE)
        state["conversation_id"] = str(conv.id)
        _save_state(state)
    out.conversation_id = state["conversation_id"]

    answers: list[tuple[dict, str]] = []
    for spec in DASHBOARD_WIDGETS:
        message_id, error = _ask(org_id, user_id, tenant, UUID(state["conversation_id"]), spec["question"])
        if message_id:
            answers.append((spec, message_id))
        else:
            out.warnings.append(f"'{spec['question']}' was not answered ({error}); its widget was skipped.")
    if not answers:
        out.warnings.append("No question was answered: the dashboard was not created.")
        return
    with tenant_context(org_id, info=tenant):
        dash = bi.create_dashboard(user_id=user_id, title=DASHBOARD_TITLE, is_default=True,
                                   description="Revenue KPIs of the synthetic sales dataset (seed_demo).")
        for spec, message_id in answers:
            bi.add_widget(dash, org_id=org_id, user_id=user_id, title=spec["title"], kind=spec["kind"],
                          message_id=message_id, layout=spec["layout"])
            out.widgets.append(spec["title"])
        state["dashboard_id"] = str(dash.id)
        _save_state(state)
    out.dashboard_id = state["dashboard_id"]


# ------------------------------------------------------------------------------------------------ entry point
def seed_demo(*, email: str = DEFAULT_EMAIL, password: str | None = None, org_name: str = DEFAULT_ORG_NAME,
              reset: bool = False, directory: Path | None = None,
              progress: Callable[[str], None] = lambda _msg: None) -> SeedResult:
    from apps.accounts.services import ensure_user
    from apps.core.tenancy import tenant_context
    from apps.core.tenancy.views import resolve_membership
    from apps.orgs.services import create_organization, effective_ai_policy, get_current_org

    directory = directory or data_dir()
    files = ensure_test_data(directory)
    generated = None
    user, user_created = ensure_user(email, password=password, full_name=DEFAULT_FULL_NAME)
    if user_created and not password:
        generated = generate_password()
        user, _ = ensure_user(email, password=generated)
    note = "set from --password" if password else ("generated" if generated else "unchanged (use --password to set)")

    with eager_tasks(), acting_as(user.pk):
        found = _find_org(user.pk, org_name)
        org_created = found is None
        if org_created:
            org = create_organization(name=org_name, owner=user)
            org_id, slug = org.id, org.slug
        else:
            org_id, slug = UUID(str(found["id"])), found["slug"]
        tenant = resolve_membership(user.pk, slug)
        if tenant is None:
            raise SeedError(f"{email} is not an active member of {slug}.")
        with tenant_context(org_id):
            state = _seed_state()
        if reset and state:
            progress("Removing the previous demo content (--reset) ...")
            _reset(org_id, user.pk, state)
            state = {}
        with tenant_context(org_id):
            policy = effective_ai_policy(get_current_org())
        out = SeedResult(email=user.email, password=password or generated, password_note=note,
                         user_created=user_created, org_id=str(org_id), org_slug=slug, org_name=org_name,
                         org_created=org_created, ai_data_policy=policy)

        recorded: dict = dict(state.get("datasets") or {})
        for path in files:
            progress(f"Ingesting {path.name} ...")
            result = _ingest(org_id, user.pk, path, recorded.get(path.name))
            out.datasets.append(result)
            if result.dataset_id:
                recorded[path.name] = result.dataset_id
                state["datasets"] = recorded
                with tenant_context(org_id):
                    _save_state(state)
            if result.status != "ready":
                out.warnings.append(f"{path.name}: ingestion did not finish ({result.status}; {result.error}).")

        sales = next((d for d in out.datasets if d.file == SALES_FILE and d.status == "ready"), None)
        if sales is None:
            out.warnings.append("sales.csv is not ready: the sample conversation and dashboard were skipped.")
        else:
            progress("Answering the sample questions and building the dashboard ...")
            _seed_bi(org_id, user.pk, tenant, sales.dataset_id, state, out)
    return out


def format_summary(r: SeedResult) -> str:
    lines = [
        "",
        "NEXORA demo data",
        "================",
        f"Login     : {r.email}",
        f"Password  : {r.password if r.password else '(' + r.password_note + ')'}",
        f"Org       : {r.org_name} (slug '{r.org_slug}', {'created' if r.org_created else 'existing'})",
        f"AI policy : {r.ai_data_policy}",
        "",
        f"{'Dataset':<34} {'Status':<10} {'Rows':>8} {'Cols':>5} {'Quality':>8}  Action",
    ]
    for d in r.datasets:
        quality = f"{d.quality:.1f}" if d.quality is not None else "-"
        rows = str(d.rows) if d.rows is not None else "-"
        cols = str(d.columns) if d.columns is not None else "-"
        lines.append(f"{d.name[:34]:<34} {d.status:<10} {rows:>8} {cols:>5} {quality:>8}  {d.action}")
    lines.append(f"{'Total rows (ready datasets)':<34} {'':<10} {r.total_rows:>8}")
    lines.append("")
    lines.append(f"Conversation : {r.conversation_id or '-'}")
    lines.append(f"Dashboard    : {r.dashboard_id or '-'} ({len(r.widgets)} widgets: {', '.join(r.widgets) or '-'})")
    for w in r.warnings:
        lines.append(f"WARNING: {w}")
    return "\n".join(lines)
