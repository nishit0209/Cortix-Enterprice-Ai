"""`manage.py seed_demo`: demo content through the REAL services (CONTRACT "Local runtime: Demo data").

Everything the demo shows comes from real database rows produced by the normal product paths:

  1. a demo user (accounts.services.ensure_user) and an org (orgs.services.create_organization: AI data policy
     `synthetic_only`, which this command never changes);
  2. every synthetic CSV in testdata/generated/ (generated by testdata/generate.py when missing) uploaded and
     ingested with `datasets.services.create_upload` + `create_dataset` (classification `synthetic`, attested by the
     demo user). The task runner is forced to "eager", so profiling, quality, the warehouse load and the semantic
     layer finish before the command continues;
  3. one sample BI conversation on the sales dataset whose questions are answered by the real chat pipeline
     (deterministic SQL builder, guarded and audited), and a default dashboard whose widgets pin those answers
     (each widget re-runs its saved query under the viewer's policy).

Idempotent: what was created is remembered in the org's `settings.demo_seed`; a re-run only fills what is
missing (or failed). `reset=True` removes the demo datasets, dashboard and conversation first.
"""

